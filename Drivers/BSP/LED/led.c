/*
    这个文件来写led的实现，逻辑上来说非常简单，也是我好久没写裸机的第一次学习
    | PA11 | LED1    
    | PD2  | LED2    
    对于GPIO外设的使用，我们一般分为1.启动时钟，2设置gpio口模式，3初始化位某一个电平，4对其操作
    注意某些io口不仅可以作为gpio，在某些情况下它默认为一些特殊功能的引脚入JTAG，我们必须要先看原理图然后才进行实际的操作

    PA11 44 I/O 5VT
    Default: PA11
    Alternate: USART0_CTS, CAN0_RX, USBDM, TIMER0_CH3
    PD2 54 I/O 5VT
    Default: PD2
    Alternate: TIMER2_ETI, SDIO_CMD(4), UART4_RX(4)

    从数据手册的GD32F103Rx LQFP64 pin definitions中截取看出PA11,PD2在default情况都是默认的io口，因此不用进行重映射等操作
*/
#include "led.h"
#include "gd32f10x.h"
#include "gd32f10x_gpio.h"
#include "gd32f10x_rcu.h"

// LED1 对应 PA11
#define LED1_PORT          GPIOA
#define LED1_PIN           GPIO_PIN_11

// LED2 对应 PD2
#define LED2_PORT          GPIOD
#define LED2_PIN           GPIO_PIN_2

void led_init()
{
    //第一步使能时钟
    rcu_periph_clock_enable(RCU_GPIOA);
    rcu_periph_clock_enable(RCU_GPIOD);

    //第二部，初始化gpio配置
    gpio_init(LED1_PORT, GPIO_MODE_OUT_PP, GPIO_OSPEED_50MHZ, LED1_PIN);
    gpio_init(LED2_PORT, GPIO_MODE_OUT_PP, GPIO_OSPEED_50MHZ, LED2_PIN);
   /*
    这里值得重点说明的是 GPIO 的工作模式。
    GPIO_MODE_AIN            模拟输入
    GPIO_MODE_IN_FLOATING    浮空输入
    GPIO_MODE_IPD            下拉输入
    GPIO_MODE_IPU            上拉输入
    GPIO_MODE_OUT_OD         普通开漏输出
    GPIO_MODE_OUT_PP         普通推挽输出
    GPIO_MODE_AF_OD          复用开漏输出
    GPIO_MODE_AF_PP          复用推挽输出

    从大的方向来看，可以先分成输入和输出两类。
    关于输入，代表着这个 IO 口主要用于读取外部信号。
    模拟输入主要用于读取模拟信号，比如 ADC 输入。在这种模式下，GPIO 的数字输入输出功能通常会被关闭，信号直接交给 ADC 等模拟外设处理。
    浮空输入、上拉输入和下拉输入都属于数字输入模式。
    浮空输入表示 MCU 内部没有主动使用上拉或下拉电阻，因此引脚电平完全由外部电路决定。如果外部没有稳定的高低电平来源，引脚可能会受到干扰而出现不确定状态。
    上拉输入和下拉输入则是在 MCU 内部给引脚增加一个较弱的默认电平。
    上拉输入意味着在外部没有信号驱动的时候，引脚会倾向于保持高电平；下拉输入则会倾向于保持低电平。
    所以内部上下拉的主要作用，是避免输入引脚在外部悬空的时候出现不稳定的电平。
    例如按键输入中，就经常会使用内部上拉或者内部下拉。
    不过需要注意，不同通信外设的引脚模式并不能简单地概括成“串口、SPI、IIC 都使用浮空输入”。
    例如 UART 中，如果 MCU 的 TX 引脚负责发送数据，那么 TX 一般使用复用推挽输出；而 RX 是输入端，可以配置成浮空输入或者上拉输入。
    SPI 也一样。
    如果 MCU 工作在 SPI 主机模式，那么 SCK 和 MOSI 通常由 MCU 输出，因此一般使用复用推挽输出；MISO 是 MCU 接收数据的输入引脚，因此可以使用输入模式。
    IIC 则更加特殊，因为 SDA 和 SCL 一般采用开漏结构，所以在使用硬件 IIC 外设的时候，GPIO 通常配置成复用开漏模式。
    关于输出，可以继续分成推挽输出和开漏输出。
    推挽输出的内部一般同时存在上拉驱动管和下拉驱动管，因此它既可以主动输出高电平，也可以主动输出低电平。
    当输出 1 时，内部上拉管导通，下拉管关闭，引脚会被 MCU 主动拉到高电平。
    当输出 0 时，内部下拉管导通，上拉管关闭，引脚会被 MCU 主动拉到低电平。
    所以推挽输出的驱动能力比较强，适合 LED、普通数字控制信号、UART TX、SPI 时钟等大多数需要 MCU 主动输出高低电平的场景。
    而开漏输出和推挽输出最大的区别，在于开漏一般只有一个下拉 NMOS。
    当我们向开漏输出写 0 时，内部 NMOS 导通，引脚被主动拉到低电平。
    当我们向开漏输出写 1 时，并不是 MCU 主动输出高电平，而是关闭内部 NMOS，让引脚进入高阻态。
    所以开漏输出实际上只有两种状态：
    第一种是主动拉低。
    第二种是释放线路，也就是高阻态。
    如果希望开漏输出能够得到高电平，就必须依赖外部上拉电阻。
    例如外部通过一个电阻连接到 3.3V，那么当 MCU 输出 1、进入高阻态以后，因为 MCU 不再主动拉低引脚，所以外部上拉电阻就会把线路拉到 3.3V。
    当 MCU 输出 0 时，内部 NMOS 导通，引脚又会被拉到 GND。
    因此开漏输出的逻辑可以理解为：
    输出 0 = 主动拉低。
    输出 1 = 不主动输出高电平，而是释放总线。
    这也是 IIC 为什么大量使用开漏结构的原因。
    IIC 是一种共享总线通信协议，同一根 SDA、SCL 线路上可能连接多个设备。
    如果所有设备都使用推挽输出，就可能出现一个设备主动输出高电平，而另一个设备主动输出低电平的情况。
    例如设备 A 推挽输出 3.3V，设备 B 推挽输出 0V，那么两个设备就在同一根线上互相“对抗”，这叫做总线争用。
    这时候会产生很大的电流，严重时甚至可能损坏 IO 口。
    而如果所有设备都使用开漏结构，就不会出现这种情况。
    因为所有设备都只能主动拉低，不能主动拉高。
    例如设备 A 想发送 1，它实际上只是释放总线，进入高阻态。
    设备 B 如果此时想发送 0，就可以直接把线路拉低。
    因为设备 A 并没有主动输出高电平，所以不会和设备 B 发生电气冲突。
    如果所有设备都释放总线，也就是全部处于高阻态，那么外部上拉电阻就会把总线拉到高电平。
    所以从物理层来看，IIC 的逻辑其实可以简单理解为：
    逻辑 0：至少有一个设备正在主动拉低总线。
    逻辑 1：没有任何设备拉低总线，由外部上拉电阻把线路拉高。
    这就是开漏结构特别适合共享总线的原因。
    这里还要重点理解什么叫高阻态。
    所谓高阻态，并不是一种高电平，也不是一种低电平。
    它表示 MCU 的输出驱动电路基本从这根线路上“断开”了，对外表现出一个非常大的阻抗。
    也就是说 MCU 此时既不主动把线路拉高，也不主动把线路拉低。
    线路最终是什么电平，完全由外部电路决定。
    如果外部通过电阻上拉到 3.3V，那么高阻态时引脚就是 3.3V。
    如果外部设备把线路拉到 0V，那么引脚就是 0V。
    如果外部没有任何稳定的驱动，线路甚至可能出现不确定电平。
    所以高阻态是一种“驱动状态”，而不是一种具体的电压状态。
    这也是为什么设置为开漏输出并写入 1 以后，MCU 仍然可以读取到外部设备改变后的线路电平。
    因为这时候 MCU 自己已经不再驱动线路，外部设备可以决定这根线的实际高低电平，而 MCU 的输入检测电路依旧可以读取这个电平。
    开漏还有另外一个很有用的地方，就是电平兼容。
    例如一个 MCU 工作电压是 3.3V，如果某个 GPIO 支持 5V tolerant，也就是数据手册中标注为 5VT，那么可以让这个开漏引脚通过外部电阻上拉到 5V。
    当 MCU 输出 0 时，内部 NMOS 把引脚拉低到 0V。
    当 MCU 输出 1 时，内部进入高阻态，引脚会被外部上拉电阻拉到 5V。
    这样就可以在一定条件下实现 3.3V MCU 和 5V 逻辑电路之间的兼容。
    但是一定要注意，这并不代表所有 3.3V GPIO 都可以直接上拉到 5V。
    是否能够承受 5V，必须查看对应 GPIO 在芯片数据手册中是否明确支持 5V tolerant。
    接下来再看普通输出和复用输出的区别。
    普通输出和复用输出最核心的区别，不是推挽和开漏，而是谁在控制这个 GPIO 引脚。
    普通 GPIO 输出时，引脚由 GPIO 外设自己控制。
    例如：
    GPIO_MODE_OUT_PP
    表示 GPIO 外设控制这个引脚，并且使用推挽方式输出。
    GPIO_MODE_OUT_OD
    表示 GPIO 外设控制这个引脚，并且使用开漏方式输出。
    这时候我们通常会直接调用：
    gpio_bit_set()
    gpio_bit_reset()
    通过 CPU 修改 GPIO 寄存器，从而控制引脚高低电平。
    而复用功能则表示这个 GPIO 的控制权交给 MCU 内部的其他硬件外设。
    例如 UART、SPI、IIC、TIMER 等。
    GPIO_MODE_AF_PP
    表示由某个片上外设控制这个引脚，同时使用推挽方式进行输出。
    GPIO_MODE_AF_OD
    表示由某个片上外设控制这个引脚，同时使用开漏方式进行输出。
    例如使用硬件 SPI 时，SCK、MOSI 等引脚可以配置成复用推挽输出。
    此时不需要 CPU 自己不断调用 gpio_bit_set() 和 gpio_bit_reset() 去模拟 SPI 时序，而是由 SPI 硬件外设自动控制这些引脚。
    CPU 只需要把需要发送的数据写入 SPI 外设，真正什么时候拉高 SCK、什么时候拉低 SCK、什么时候改变 MOSI，都由 SPI 外设硬件自动完成。
    IIC 也是类似的。
    如果我们使用软件模拟 IIC，那么 SDA 和 SCL 仍然由普通 GPIO 控制。
    CPU 需要自己通过 gpio_bit_set()、gpio_bit_reset() 等操作模拟起始位、停止位、ACK、时钟以及数据变化。
    这种情况下可以使用普通开漏 GPIO，或者通过输入输出切换的方式模拟开漏效果。
    而如果我们使用 MCU 内部真正的硬件 IIC 外设，那么 SDA、SCL 一般会配置成复用开漏模式。
    这时候 CPU 不需要直接控制 SDA、SCL 每一个电平变化，而是通过 IIC 外设寄存器发送地址和数据。
    真正的总线时序由 IIC 硬件自动产生。
    所以可以简单总结为：
    OUT_PP：GPIO 控制 + 推挽输出。
    OUT_OD：GPIO 控制 + 开漏输出。
    AF_PP：片上外设控制 + 推挽输出。
    AF_OD：片上外设控制 + 开漏输出。
    这里还要注意一个问题。
    “复用”并不等于“重新映射”。
    复用表示这个 IO 引脚正在被某个片上外设使用，而不是普通 GPIO。
    重映射则表示某个外设原本默认连接在一组 GPIO 上，但是我们通过 AFIO 等配置，把这个外设移动到另外一组可选引脚。
    例如某个 USART 默认使用 PA9、PA10，但芯片可能允许通过 remap 把它重新映射到其他 GPIO。
    因此：
    复用功能 = GPIO 交给外设控制。
    重映射 = 修改这个外设究竟连接到哪一组 GPIO。
    这是两个不同的概念。
    最后再来看 GPIO 的输出速度参数。
    GPIO_OSPEED_2MHZ
    GPIO_OSPEED_10MHZ
    GPIO_OSPEED_50MHZ
    这个参数主要用于设置 GPIO 的输出驱动速度等级。
    它会影响 GPIO 输出信号的上升沿、下降沿以及驱动能力。
    一般来说，速度等级越高，信号边沿越快，适合高速数字信号。
    速度等级越低，信号边沿越缓和。
    但是 GPIO_OSPEED_2MHZ 并不能简单理解为这个 GPIO 最多只能输出 2MHz 的方波。
    GPIO 实际能够翻转多快，还受到 CPU 主频、总线频率、指令执行速度、外设硬件等很多因素影响。
    所以这个参数更应该理解为 GPIO 输出级的边沿速度和驱动能力等级。
    高速模式虽然可以让信号边沿更快，但是也会带来更强的 EMI、电磁干扰、振铃等问题。
    因此没有必要所有 GPIO 都直接设置为 50MHz。
    例如 LED、按键控制之类的低速信号，使用 2MHz 就已经完全足够。
    而 SPI、PWM、高速时钟等信号，则可以根据实际通信速度选择更高的 GPIO 输出速度。
    所以 GPIO 配置时可以形成一个基本思路：
    第一步，根据功能判断这是输入还是输出。
    第二步，如果是输出，判断需要推挽还是开漏。
    第三步，判断这个引脚由普通 GPIO 控制，还是由 UART、SPI、IIC、TIMER 等片上外设控制。
    第四步，再根据实际信号速度选择合适的 GPIO 输出速度。
    这样基本就可以判断应该使用哪一种 GPIO 模式。
*/
    //第三步，设置初始电平为低（reset）
    gpio_bit_reset(LED1_PORT,LED1_PIN);
    gpio_bit_reset(LED2_PORT, LED2_PIN);
}

void led1_toggle()
{
    //这里要干的事情是不管原来的怎么样翻转一次电平
    //我们只需要读取一下现在的电平然后设置为相反的就好
    FlagStatus led1_flags = gpio_output_bit_get(LED1_PORT, LED1_PIN);
    if(led1_flags == SET)
    {
        gpio_bit_reset(LED1_PORT, LED1_PIN);
    }
    else
    {
        gpio_bit_set(LED1_PORT, LED1_PIN);
    }
}

void led1_on()
{
    gpio_bit_set(LED1_PORT, LED1_PIN);
}

void led1_off()
{
    gpio_bit_reset(LED1_PORT, LED1_PIN);
}

void led2_toggle()
{
    FlagStatus led2_flags = gpio_output_bit_get(LED2_PORT, LED2_PIN);
    if(led2_flags == SET)
    {
        gpio_bit_reset(LED2_PORT, LED2_PIN);
    }
    else
    {
        gpio_bit_set(LED2_PORT, LED2_PIN);
    }
}