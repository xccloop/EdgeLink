/*
    下标 = 字符码 - 32，因为表里第一行是 ASCII 32（空格）。
    column 只有 0~4 这 5 列。
*/
uint8_t hmi_font_column(uint8_t character, uint8_t column)
{
    if(column >= 5U) return 0U;
    if((character < 32U) || (character > 127U)) character = '?';
    return font_columns[character - 32U][column];
}